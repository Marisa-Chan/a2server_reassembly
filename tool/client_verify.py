#!/usr/bin/env python
"""Client (allods2.exe) verification queue driver.

Files:
    migration_state/client_verify_queue.txt   the TODO list (auto-generated)
    migration_state/client_verified.txt       append-only log of results

Commands:
    regen                              rebuild the queue from the diff artifacts
    next                               print the next actionable item
    class <Class>                      per-class report incl. referenced-string check
    record-identical <Class>           verify a class's identical batch (string check)
                                       and move it to the log; pairs with string
                                       mismatches stay in the queue as FLAGGED
    done <Class> <server_va|method>    mark a DIFFERS/CLIENT_ONLY item ported
"""
import argparse
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import client_fn_diff as fnd

ROOT = os.path.dirname(HERE)
STATE = os.path.join(ROOT, 'migration_state')
QUEUE = os.path.join(STATE, 'client_verify_queue.txt')
LOG = os.path.join(STATE, 'client_verified.txt')

QUEUE_HEADER = """\
# Auto-generated by tool/client_verify.py regen - client (allods2.exe) verification TODO.
# Line format (tab-separated): STATUS<TAB>class<TAB>method<TAB>server_va<TAB>client_va<TAB>basis
#   DIFFERS      port the client version of this method (one commit per function)
#   CLIENT_ONLY  new client-side method - port it
#   FLAGGED      identical code but referenced strings differ - inspect manually
#   BATCH        all-identical class: run `client_verify.py record-identical <Class>`
# Do not edit by hand; use tool/client_verify.py.
"""

LOG_HEADER = """\
# Auto-generated log, appended by tool/client_verify.py. One line per result:
#   IDENTICAL <class> <method> <srv_va> <cli_va> [strings-ok]   (batch-verified)
#   IDENTICAL-BATCH <class> <n>                                  (batch marker)
#   FLAGGED <class> <method> <srv_va> <cli_va>                   (strings differ)
#   PORTED <class> <method> <srv_va> <cli_va>                    (client version ported)
"""


def repo_classes():
    cls = set()
    pat = re.compile(r'^\s*(?:class|struct)\s+([A-Za-z_]\w*)')
    for path in glob.glob(os.path.join(ROOT, 'src', '*.h')):
        for ln in open(path, encoding='utf-8', errors='replace'):
            m = pat.match(ln)
            if m:
                cls.add(m.group(1))
    return cls


def read_log():
    ported, batches = set(), set()
    if not os.path.exists(LOG):
        return ported, batches
    for ln in open(LOG, encoding='utf-8'):
        p = ln.split()
        if p and p[0] == 'PORTED' and len(p) >= 4:
            ported.add((p[1], p[3]))
        elif p and p[0] == 'IDENTICAL-BATCH' and len(p) >= 2:
            batches.add(p[1])
    return ported, batches


def read_queue():
    items = []
    for ln in open(QUEUE, encoding='utf-8'):
        if ln.startswith('#') or not ln.strip():
            continue
        items.append(ln.rstrip('\n').split('\t'))
    return items


def class_order_key(cls):
    """workload-first ordering (largest client bytes first), Vis* before the rest"""
    rec = fnd.artifacts()['cm']['classes'].get(cls, {})
    d = sum(v for k, v in rec.get('counts', {}).items())  # rough presence
    rows = rec.get('cli_vts') or []
    return (0 if cls.startswith('Vis') else 1, cls)


def cmd_regen():
    ar = fnd.artifacts()
    repo = repo_classes()
    ported, batches_done = read_log()
    blocks = []
    n_diff = n_cli = n_batch = 0
    for cls in sorted(ar['cm']['classes']):
        if cls not in repo and not cls.startswith('Vis'):
            continue
        t = fnd.class_table(cls)
        if t is None:
            continue
        rows = t['rows']
        open_items = []
        n_id = 0
        for r in rows:
            if r['status'] == 'DIFFERS' and (cls, r['server_va']) not in ported:
                open_items.append(('DIFFERS', cls, r['method'], r['server_va'], r['client_va'], r['basis']))
            elif r['status'] == 'CLIENT_ONLY' and (cls, r['method']) not in ported:
                open_items.append(('CLIENT_ONLY', cls, r['method'], '-', r['client_va'], r['basis']))
            elif r['status'] == 'IDENTICAL':
                n_id += 1
        if not open_items and n_id and cls not in batches_done:
            open_items.append(('BATCH', cls, '%d identical fns' % n_id, '-', '-', '-'))
        if open_items:
            blocks.append((cls, open_items))
            n_diff += sum(1 for i in open_items if i[0] == 'DIFFERS')
            n_cli += sum(1 for i in open_items if i[0] == 'CLIENT_ONLY')
            n_batch += sum(1 for i in open_items if i[0] == 'BATCH')
    blocks.sort(key=lambda b: class_order_key(b[0]))
    with open(QUEUE, 'w', encoding='utf-8') as fh:
        fh.write(QUEUE_HEADER)
        for cls, items in blocks:
            fh.write('# === %s ===\n' % cls)
            for it in items:
                fh.write('\t'.join(it) + '\n')
    print('queue: %d classes, %d DIFFERS, %d CLIENT_ONLY, %d BATCH items -> %s' % (
        len(blocks), n_diff, n_cli, n_batch, QUEUE))


def cmd_next():
    for it in read_queue():
        if it[0] in ('DIFFERS', 'CLIENT_ONLY', 'FLAGGED', 'BATCH'):
            print('\t'.join(it))
            return
    print('queue empty')


def string_check(srv_va, cli_va):
    ar = fnd.artifacts()
    s = set()
    for t in ar['srv']['datarefs'].get('%x' % srv_va, []):
        if t in ar['srv']['strings']:
            s.add(ar['srv']['strings'][t])
    c = set()
    for t in ar['cli']['datarefs'].get('%x' % cli_va, []):
        if t in ar['cli']['strings']:
            c.add(ar['cli']['strings'][t])
    return s, c


def cmd_class(cls):
    t = fnd.class_table(cls)
    if t is None:
        print('class not in map:', cls)
        return
    print(t['header'])
    print()
    print('%-12s %-28s %-9s %-9s %-7s %-7s %-10s %s' % (
        'status', 'method', 'srv', 'cli', 'srv_sz', 'cli_sz', 'strings', 'basis'))
    for r in t['rows']:
        s = c = ()
        note = '-'
        if r['status'] == 'IDENTICAL' and r['server_va'] and r['client_va']:
            s, c = string_check(int(r['server_va'], 16), int(r['client_va'], 16))
            note = 'ok' if s == c else 'DIFFER'
        print('%-12s %-28s %-9s %-9s %-7d %-7d %-10s %s' % (
            r['status'], r['method'][:28], r['server_va'] or '-', r['client_va'] or '-',
            r['server_size'], r['client_size'], note, r['basis']))
        if note == 'DIFFER':
            print('    server-only strings: %r' % sorted(s - c)[:5])
            print('    client-only strings: %r' % sorted(c - s)[:5])


def cmd_record_identical(cls):
    t = fnd.class_table(cls)
    if t is None:
        print('class not in map:', cls)
        return
    ar = fnd.artifacts()
    clean, flagged = [], []
    for r in t['rows']:
        if r['status'] != 'IDENTICAL' or not r['server_va'] or not r['client_va']:
            continue
        s, c = string_check(int(r['server_va'], 16), int(r['client_va'], 16))
        (clean if s == c else flagged).append((r, s, c))
    with open(LOG, 'a', encoding='utf-8') as fh:
        if clean:
            for r, _, _ in clean:
                fh.write('IDENTICAL\t%s\t%s\t%s\t%s\tstrings-ok\n' % (
                    cls, r['method'], r['server_va'], r['client_va']))
            fh.write('IDENTICAL-BATCH\t%s\t%d\n' % (cls, len(clean)))
    if flagged:
        with open(QUEUE, 'a', encoding='utf-8') as fh:
            for r, s, c in flagged:
                fh.write('FLAGGED\t%s\t%s\t%s\t%s\tstring-mismatch\n' % (
                    cls, r['method'], r['server_va'], r['client_va']))
    # drop the BATCH line (and any FLAGGED lines now recorded) for this class
    items = [it for it in read_queue()
             if not (it[0] == 'BATCH' and len(it) > 1 and it[1] == cls)]
    _write_items(items)
    print('recorded %d identical (strings-ok), %d flagged for string mismatch' % (len(clean), len(flagged)))


def _write_items(items):
    with open(QUEUE, 'w', encoding='utf-8') as fh:
        fh.write(QUEUE_HEADER)
        for it in items:
            fh.write('\t'.join(it) + '\n')


def cmd_done(cls, key):
    items = read_queue()
    out = []
    hit = None
    for it in items:
        if it[0] in ('DIFFERS', 'CLIENT_ONLY', 'FLAGGED') and it[1] == cls and key in (it[3], it[2]):
            hit = it
            continue
        out.append(it)
    if hit is None:
        print('no open item for %s matching %r' % (cls, key))
        return
    with open(LOG, 'a', encoding='utf-8') as fh:
        fh.write('PORTED\t%s\t%s\t%s\t%s\n' % (cls, hit[2], hit[3], hit[4]))
    _write_items(out)
    print('done: %s %s (%s)' % (cls, hit[2], hit[0]))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('regen')
    sub.add_parser('next')
    p = sub.add_parser('class')
    p.add_argument('cls')
    p = sub.add_parser('record-identical')
    p.add_argument('cls')
    p = sub.add_parser('done')
    p.add_argument('cls')
    p.add_argument('key', help='server_va (preferred) or method name')
    a = ap.parse_args()
    if not os.path.exists(LOG):
        with open(LOG, 'w', encoding='utf-8') as fh:
            fh.write(LOG_HEADER)
    {'regen': lambda: cmd_regen(), 'next': lambda: cmd_next(),
     'class': lambda: cmd_class(a.cls), 'record-identical': lambda: cmd_record_identical(a.cls),
     'done': lambda: cmd_done(a.cls, a.key)}[a.cmd]()


if __name__ == '__main__':
    main()
