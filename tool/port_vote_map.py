# One-off: port #vote_map into Server::CheatCommand (server.cpp).
BS = chr(92)
Q = chr(39)  # single quote

text = open('src/server.cpp', 'rb').read().decode('utf-8')

old = ('            g_NetStru1_main.AnnouncePlayerName(msg, player);\r\n'
       '            return;\r\n'
       '        }\r\n'
       '\r\n')
assert old in text, "mapinfo tail anchor not found"

L = []
L.append('        if (lowered.Find("#vote_map") == 0) {')
L.append('            // Tangar #vote_map (ProcessCheat_VoteMap): players vote for the next')
L.append('            // map; the leading map is rotated into the slot after the current one.')
L.append('            // Only active on the QUEST_T1 server.')
L.append('            bool vote_applied = false;')
L.append('            if (Config::ServerID == QUEST_T1) {')
L.append('                CStringArray& map_files = g_ServerConfig.map_names;')
L.append('                CDWordArray& map_times = g_ServerConfig.map_durations;')
L.append('                int32_t map_index = (int32_t)g_ServerConfig.current_map_index;')
L.append('')
L.append('                if (map_index == map_files.GetSize() - 1) {')
L.append('                    g_NetStru1_main.AnnouncePlayerName("This is the last map in the pool, voting is closed. The next map will be chosen randomly.", player);')
L.append('                } else if (map_index == map_files.GetSize() - 2) {')
L.append('                    g_NetStru1_main.AnnouncePlayerName("There is only one map left in the pool, voting is closed.", player);')
L.append('                } else {')
L.append('                    // Map basenames for easier matching.')
L.append('                    std::vector<CString> all_map_names;')
L.append('                    for (int32_t i = 0; i < map_files.GetSize(); i++) {')
L.append('                        CString name = map_files[i];')
L.append('                        int32_t slash = name.ReverseFind(' + Q + BS + Q + ');')
L.append('                        int32_t slash2 = name.ReverseFind(' + Q + '/' + Q + ');')
L.append('                        if (slash2 > slash) {')
L.append('                            slash = slash2;')
L.append('                        }')
L.append('                        if (slash >= 0) {')
L.append('                            name = name.Mid(slash + 1);')
L.append('                        }')
L.append('                        all_map_names.push_back(name);')
L.append('                    }')
L.append('')
L.append('                    CString args = cheat_string.Mid(9);')
L.append('                    args.TrimLeft();')
L.append('                    args.TrimRight();')
L.append('')
L.append('                    settings::PlayerSettings* player_settings = settings::FindOrCreate((const char*)player->name);')
L.append('')
L.append('                    if (args.GetLength() > 0) {')
L.append('                        std::vector<CString> matching_maps;')
L.append('                        for (int32_t i = map_index + 1; i < map_files.GetSize(); i++) {')
L.append('                            if (all_map_names[i].Find((const char*)args) >= 0) {')
L.append('                                matching_maps.push_back(all_map_names[i]);')
L.append('                            }')
L.append('                        }')
L.append('')
L.append('                        if (matching_maps.size() == 0) {')
L.append('                            CString m;')
L.append('                            m.Format("Map ' + Q + '%s' + Q + ' is not available for selection", (const char*)args);')
L.append('                            g_NetStru1_main.AnnouncePlayerName(m, player);')
L.append('                        } else if (matching_maps.size() > 1) {')
L.append('                            CString names;')
L.append('                            for (size_t i = 0; i < matching_maps.size(); i++) {')
L.append('                                if (names.GetLength() > 0) {')
L.append('                                    names += ", ";')
L.append('                                }')
L.append('                                names += matching_maps[i];')
L.append('                            }')
L.append('                            CString m;')
L.append('                            m.Format("Multiple maps match ' + Q + '%s' + Q + ': %s", (const char*)args, (const char*)names);')
L.append('                            g_NetStru1_main.AnnouncePlayerName(m, player);')
L.append('                        } else {')
L.append('                            CString m;')
L.append('                            m.Format("You voted for map ' + Q + '%s' + Q + '", (const char*)matching_maps[0]);')
L.append('                            g_NetStru1_main.AnnouncePlayerName(m, player);')
L.append('                            player_settings->map_vote = (const char*)matching_maps[0];')
L.append('                            player_settings->last_modified = time(nullptr);')
L.append('                        }')
L.append('                    }')
L.append('')
L.append('                    // Current votes.')
L.append('                    std::map<std::string, int32_t> current_votes;')
L.append('                    settings::ForEachReadonly([&current_votes](const std::string& name, settings::PlayerSettings* ps) {')
L.append('                        (void)name;')
L.append('                        if (!ps->map_vote.empty()) {')
L.append('                            current_votes[ps->map_vote]++;')
L.append('                        }')
L.append('                    });')
L.append('')
L.append('                    if (args.GetLength() == 0) {')
L.append('                        // No vote cast: show the current tally.')
L.append('                        for (auto vote_it = current_votes.begin(); vote_it != current_votes.end(); ++vote_it) {')
L.append('                            CString m;')
L.append('                            m.Format("Map ' + Q + '%s' + Q + ' has %d votes", vote_it->first.c_str(), vote_it->second);')
L.append('                            g_NetStru1_main.AnnouncePlayerName(m, player);')
L.append('                        }')
L.append('                    } else {')
L.append('                        // Which map is the most voted now? Ties cancel out.')
L.append('                        int32_t most_votes = -1;')
L.append('                        std::string next_map;')
L.append('                        for (auto vote_it = current_votes.begin(); vote_it != current_votes.end(); ++vote_it) {')
L.append('                            if (vote_it->second == most_votes) {')
L.append('                                next_map = "";')
L.append('                            } else if (vote_it->second > most_votes) {')
L.append('                                most_votes = vote_it->second;')
L.append('                                next_map = vote_it->first;')
L.append('                            }')
L.append('                        }')
L.append('')
L.append('                        int32_t next_map_index = -1;')
L.append('                        if (!next_map.empty()) {')
L.append('                            for (int32_t i = 0; i < map_files.GetSize(); i++) {')
L.append('                                if (strcmp((const char*)all_map_names[i], next_map.c_str()) == 0) {')
L.append('                                    next_map_index = i;')
L.append('                                }')
L.append('                            }')
L.append('')
L.append('                            if (next_map_index != -1 && next_map_index > map_index + 1) {')
L.append('                                // Rotate names and durations so the voted map follows')
L.append('                                // the current one (std::rotate(begin, middle, end)).')
L.append('                                CString chosen_name = map_files[next_map_index];')
L.append('                                uint32_t chosen_duration = map_times[next_map_index];')
L.append('                                for (int32_t i = next_map_index; i > map_index + 1; i--) {')
L.append('                                    map_files[i] = map_files[i - 1];')
L.append('                                    map_times[i] = map_times[i - 1];')
L.append('                                }')
L.append('                                map_files[map_index + 1] = chosen_name;')
L.append('                                map_times[map_index + 1] = (int32_t)chosen_duration;')
L.append('                                vote_applied = true;')
L.append('                            } else if (next_map_index != -1) {')
L.append('                                CString m;')
L.append('                                m.Format("The next map will be ' + Q + '%s' + Q + ' with %d vote(s).", next_map.c_str(), most_votes);')
L.append('                                g_NetStru1_main.AnnouncePlayerName(m, player);')
L.append('                            }')
L.append('                        }')
L.append('                    }')
L.append('                }')
L.append('            }')
L.append('            if (vote_applied) {')
L.append('                server_state.ThrottledSave(); // Map order has changed, save it.')
L.append('            }')
L.append('            return;')
L.append('        }')
L.append('')

new = old + "\r\n".join(L) + "\r\n"
text = text.replace(old, new, 1)
open('src/server.cpp', 'wb').write(text.encode('utf-8'))
print("vote_map added")
